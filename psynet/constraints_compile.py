"""Constraints-file generation and freshness checks for PsyNet experiments.

This module provides :func:`generate_constraints_file`, which produces a
``constraints.txt`` from ``requirements.txt`` using Dallinger's standalone
constraints script via ``uv run``, :func:`constraints_are_up_to_date`,
which decides whether an existing lockfile still matches ``requirements.txt``,
and :func:`constraints_are_hand_written`, which identifies lockfiles that the
author maintains and PsyNet must leave alone.

That script (PEP 723, dependencies only ``click`` and ``requests``) implements
the real lock policy: resolve against the Dallinger ``dev-requirements.txt``
for the Dallinger version implied by the experiment requirements, using
``.python-version``. It does not require ``psynet[experiment]`` or an imported
Dallinger package, so thin-bootstrap ``psynet setup`` can lock before
``uv pip sync``.

When Dallinger is installed (editable or otherwise), its local
``dallinger.constraints`` script is used so generation matches the installed
package. Otherwise the script is fetched from the Dallinger release tag that
matches PsyNet's declared lower bound in ``pyproject.toml`` (never
``master``); see :mod:`psynet.dallinger_dependency`.

Dallinger's pins don't cover every package PsyNet installs, so the script also
compiles against PsyNet's own lockfile (:data:`PSYNET_CONSTRAINTS_PATH`, kept
by :mod:`psynet.dev.ci`) for the PsyNet version that ``requirements.txt`` pins.
That lockfile is read from the pinned tag or commit, because the PsyNet running
``psynet setup`` may differ from the pinned one. Unpinned or local PsyNet
requirements use the installed PsyNet's lockfile.

Callers
-------
- ``psynet.bootstrap_cli`` – ``generate-constraints`` command.
- ``psynet.experiment_setup._ensure_constraints_up_to_date`` – called during
  ``psynet setup`` to create or refresh the lockfile when missing or stale.
- ``psynet.command_line._check_constraints`` – deploy/debug verification.
"""

from __future__ import annotations

import importlib.util
import re
import shutil
import subprocess
import urllib.error
import urllib.request
from hashlib import md5
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path
from urllib.parse import quote

import click

from psynet.dallinger_dependency import dallinger_constraints_github_ref

PSYNET_CONSTRAINTS_PATH = "psynet/resources/experiment_constraints.txt"


def _dallinger_constraints_github_url() -> str:
    """Return the GitHub raw URL for Dallinger's constraints script fallback."""
    ref = dallinger_constraints_github_ref()
    return (
        "https://raw.githubusercontent.com/Dallinger/Dallinger/"
        f"{ref}/dallinger/constraints.py"
    )


def constraints_are_hand_written(constraints_path: Path | None = None) -> bool:
    """Return whether ``constraints.txt`` was written by hand.

    Follows Dallinger's rule that a lockfile without the generator's "This file
    is autogenerated" header is maintained by the author, so PsyNet neither
    regenerates it nor checks it against ``requirements.txt``. Unlike
    Dallinger, an empty file counts as missing, because installs need pins.
    """
    constraints_path = constraints_path or Path("constraints.txt")
    if not constraints_path.is_file():
        return False
    text = constraints_path.read_text()
    return bool(text.strip()) and not re.search(
        r"This file (is|was) autogenerated", text
    )


def constraints_are_up_to_date(
    *,
    requirements_path: Path | None = None,
    constraints_path: Path | None = None,
) -> bool:
    """Return whether ``constraints.txt`` matches ``requirements.txt``.

    A lockfile is up to date when it exists, is non-empty, and embeds the MD5
    digest of the current ``requirements.txt`` contents (the same signal
    ``psynet check-constraints`` uses).
    """
    requirements_path = requirements_path or Path("requirements.txt")
    constraints_path = constraints_path or Path("constraints.txt")
    if not requirements_path.is_file():
        return False
    if not constraints_path.is_file() or constraints_path.stat().st_size == 0:
        return False
    requirements_hash = md5(requirements_path.read_bytes()).hexdigest()
    return requirements_hash in constraints_path.read_text()


def generate_constraints_file() -> None:
    """Generate ``constraints.txt`` from ``requirements.txt`` in the CWD.

    Runs Dallinger's standalone constraints script with ``uv run … generate``.

    Raises
    ------
    click.ClickException
        If the requirements file is missing, ``uv`` is unavailable, or the
        constraints script fails.
    """
    requirements_path = Path("requirements.txt")
    if not requirements_path.is_file():
        raise click.ClickException(
            "requirements.txt not found. Create one before generating constraints."
        )

    if shutil.which("uv") is None:
        raise click.ClickException(
            "Could not find 'uv' on PATH. Install it with 'pip install uv' "
            "and try again."
        )

    script = _dallinger_constraints_script()
    psynet_constraints = _psynet_constraints()
    extra_args = ["--constraint", psynet_constraints] if psynet_constraints else []
    try:
        subprocess.run(
            ["uv", "run", str(script), "generate", *extra_args],
            check=True,
        )
    except subprocess.CalledProcessError as exc:
        raise click.ClickException(
            "Failed to generate constraints.txt via Dallinger's constraints "
            f"script (exit code {exc.returncode})."
        ) from exc

    constraints_path = Path("constraints.txt")
    if not constraints_path.is_file() or constraints_path.stat().st_size == 0:
        raise click.ClickException(
            "Failed to generate a non-empty constraints.txt file."
        )


def psynet_constraints_url(requirement: str) -> str | None:
    """Return the URL of PsyNet's lockfile for a pinned PsyNet requirement.

    Release pins (``psynet==14.0.0``) use the PsyNetDev tag. Git pins on GitLab
    or GitHub, including forks, use the pinned ref of that repository. Other
    requirements return ``None``. GitLab URLs use the repository files API,
    because ``/-/raw/`` answers 403 for full commit SHAs.
    """
    git = re.search(
        r"git\+(?:https://|ssh://git@)(gitlab\.com|github\.com)/"
        r"([^@#\s]+?)(?:\.git)?@([^@#\s]+)",
        requirement,
    )
    if git is not None:
        host, repository, ref = git.groups()
        if host == "github.com":
            return f"https://raw.githubusercontent.com/{repository}/{ref}/{PSYNET_CONSTRAINTS_PATH}"
        return _gitlab_file_url(repository, ref)
    release = re.fullmatch(
        r"psynet(?:\[[^\]]*\])?\s*==\s*(\S+)", requirement.strip(), re.IGNORECASE
    )
    if release is not None:
        return _gitlab_file_url("PsyNetDev/PsyNet", f"v{release.group(1)}")
    return None


def _gitlab_file_url(repository: str, ref: str) -> str:
    """Return the GitLab API URL of PsyNet's lockfile at ``ref``."""
    project = quote(repository, safe="")
    path = quote(PSYNET_CONSTRAINTS_PATH, safe="")
    return (
        f"https://gitlab.com/api/v4/projects/{project}/repository/files/{path}"
        f"/raw?ref={quote(ref, safe='')}"
    )


def _psynet_constraints() -> str | None:
    """Return the PsyNet lockfile to compile against, or ``None`` if there is none."""
    from psynet.experiment_scaffold import get_psynet_requirement

    requirement = get_psynet_requirement()
    url = psynet_constraints_url(requirement) if requirement else None
    if url is None:
        installed = Path(__file__).parents[1] / PSYNET_CONSTRAINTS_PATH
        if not installed.is_file():
            return None
        click.echo(
            "requirements.txt doesn't pin a PsyNet release or commit, so "
            f"constraints.txt uses the installed PsyNet's pins ({installed})."
        )
        return str(installed)

    try:
        with urllib.request.urlopen(url, timeout=60):
            pass
    except urllib.error.HTTPError as exc:
        if exc.code != 404:
            raise click.ClickException(
                f"Could not download PsyNet's pins from {url}: {exc}."
            ) from exc
        click.echo(
            f"PsyNet has no pins at {url} (older versions don't), so "
            "constraints.txt pins only the packages Dallinger pins."
        )
        return None
    except urllib.error.URLError as exc:
        raise click.ClickException(
            f"Could not download PsyNet's pins from {url}: {exc.reason}."
        ) from exc
    click.echo(f"Using PsyNet's pins from {url}")
    return url


def _dallinger_constraints_script() -> str:
    """Return and describe the Dallinger constraints script used by ``uv``.

    Prefers the script from an installed Dallinger package so generation matches
    that package. Thin-bootstrap environments (Dallinger not installed) use a
    pinned GitHub release URL instead of ``master``.
    """
    local_script = _installed_dallinger_constraints_script()
    if local_script is not None:
        click.echo(
            f"Using the constraints script from the installed Dallinger "
            f"({local_script}). The Dallinger version in constraints.txt comes "
            "from requirements.txt or PsyNet's Dallinger pin, not from this "
            "installation."
        )
        return str(local_script)

    ref = dallinger_constraints_github_ref()
    url = _dallinger_constraints_github_url()
    click.echo(f"Using Dallinger constraints script from GitHub ({ref}): {url}")
    return url


def _installed_dallinger_constraints_script() -> Path | None:
    """Return ``dallinger.constraints`` when Dallinger is installed."""
    try:
        distribution("dallinger")
    except PackageNotFoundError:
        return None

    spec = importlib.util.find_spec("dallinger.constraints")
    if spec is None or spec.origin is None:
        return None
    return Path(spec.origin)
