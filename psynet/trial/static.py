class StaticTrial(ChainTrial):
    """
    A Trial class for static experiments.

    The user must override the ``time_estimate`` class attribute,
    providing the estimated duration of the trial in seconds.
    This is used for predicting the participant's reward
    and for constructing the progress bar.

    Attributes
    ----------

    time_estimate : numeric
        The estimated duration of the trial (including any feedback), in seconds.
        This should generally correspond to the (sum of the) ``time_estimate`` parameters in
        the page(s) generated by ``show_trial``, plus the ``time_estimate`` parameter in
        the page generated by ``show_feedback`` (if defined).
        This is used for predicting the participant's reward
        and for constructing the progress bar.

    participant_id : int
        The ID of the associated participant.
        The user should not typically change this directly.
        Stored in ``property1`` in the database.

    answer : Object
        The response returned by the participant. This is serialised
        to JSON, so it shouldn't be too big.
        The user should not typically change this directly.
        Stored in ``details`` in the database.

    definition
        A dictionary of parameters defining the trial,
        inherited from the respective :class:`~psynet.trial.static.Stimulus` object.

    participant_group
        The associated participant group.

    block
        The block in which the trial is situated.
    """

    def show_trial(self, experiment, participant):
        raise NotImplementedError


def _layout_key(trial, page, experiment, participant):
    """Return the layout key of ``trial``'s ``page``, rendering it only once per trial.

    A page without ``#main-body`` has the key ``""``, which matches nothing.
    """
    if trial.layout_key is None:
        page._pre_render_once()
        html = page.render(experiment, participant, partial_mode=True)
        trial.layout_key = page.layout_key(html, experiment, participant) or ""
    return trial.layout_key


def _same_layout(trial, page, following, following_page, experiment, participant):
    """Whether ``following``'s page has the same layout as ``trial``'s, warning if not.

    The browser shows a trial in advance inside the current page's HTML,
    JavaScript and ``js_vars``, so a trial whose page differs in any of
    these waits for the server instead.
    """
    if not has_app_context() and None in (trial.layout_key, following.layout_key):
        # Pages can only be rendered in the experiment's app, as in a request.
        return False
    first_comparison = following.layout_key is None
    key = _layout_key(trial, page, experiment, participant)
    if key and key == _layout_key(following, following_page, experiment, participant):
        return True
    if not first_comparison:
        return False
    logger.warning(
        "Trial maker %r: the page of the trial at position %i has different "
        "HTML, JavaScript or js_vars from the one at position %i, so it can't be shown in advance and waits for the server. "
        "Put what changes between trials in the page's contents.",
        following.trial_maker_id,
        following.position,
        trial.position,
    )
    return False


class StaticTrialMaker(ChainTrialMaker):
    """
    Administers a sequence of trials in a static experiment.
    The class is intended for use with the
    :class:`~psynet.trial.static.StaticTrial` helper class.
    which should be customised to show the relevant node
    for the experimental paradigm.

    The user may also override the following methods, if desired:

    * :meth:`~psynet.trial.static.StaticTrialMaker.choose_participant_group`;
        Only relevant if the trial maker uses nodes with non-default participant groups.
        In this case the experimenter is expected to supply a function that takes participant as an argument
        and returns the chosen participant group for that trial maker.
        For example, to randomly assign participants to one of two groups called g1 and g2, one could write::

            choose_participant_group=lambda participant: random.choice(["g1", "g2"])

        Similarly, to alternate participants between two groups, one could write::

            choose_participant_group=lambda participant: ["g1", "g2"][participant.id % 2]

    * :meth:`~psynet.trial.static.StaticTrialMaker.select_node`;
      selects one of the eligible nodes for the participant's next trial.

    * :meth:`~psynet.trial.static.StaticTrialMaker.custom_node_filter`;
      filters eligible nodes before selection.

    * :meth:`~psynet.trial.main.TrialMaker.on_complete`,
      run once the sequence of trials is complete.

    * :meth:`~psynet.trial.main.TrialMaker.performance_check`;
      checks the performance of the participant
      with a view to rejecting poor-performing participants.

    * :meth:`~psynet.trial.main.TrialMaker.compute_performance_reward`;
      computes the final performance reward to assign to the participant.

    Further customisable options are available in the constructor's parameter list,
    documented below.

    Parameters
    ----------

    trial_class
        The class object for trials administered by this maker
        (should subclass :class:`~psynet.trial.static.StaticTrial`).

    nodes
        The nodes to be administered to the participants. This can be provided as
        a list of :class:`~psynet.trial.static.StaticNode` objects,
        or as a function (taking no arguments) that can be called to generate such
        a list. The latter is useful for generating nodes based on local files
        (e.g. large media assets) that are not available on the deployed server.

    expected_trials_per_participant
        Expected number of trials that each participant will complete.
        This is used for timeline/progress estimation purposes.
        This can either be an integer, or the string ``"n_nodes"``,
        which will be read as referring to the number of nodes in ``nodes``.

    max_trials_per_participant
        Maximum number of trials that each participant may complete (optional);
        once this number is reached, the participant will move on
        to the next stage in the timeline.
        This can either be an integer, or the string ``"n_nodes"``,
        which will be read as referring to the number of nodes in ``nodes``.

    recruit_mode
        Selects a recruitment criterion for determining whether to recruit
        another participant. The built-in criteria are ``"n_participants"``
        and ``"n_trials"``. ``"n_participants"`` needs
        ``target_n_participants``, and ``"n_trials"`` needs
        ``target_trials_per_node``; giving a target without its mode raises an
        error. Defaults to ``None``, which leaves recruitment to the rest of the
        experiment, for example for a practice trial maker.

    target_n_participants
        Target number of participants to recruit for the experiment. Requires
        ``recruit_mode="n_participants"``; passing it with ``None`` or
        ``"n_trials"`` raises an error. Which completions fill the quota is
        controlled by ``n_participants_completion``.

    n_participants_completion
        Which kind of completion counts toward ``target_n_participants``.
        ``"experiment"`` (default) counts participants who successfully
        finish the whole experiment. ``"trial_maker"`` counts participants
        who finish this TrialMaker, even if they later leave before the
        experiment end page. In-progress participants still occupy a slot
        in both cases, including people who have not yet reached this
        TrialMaker, so PsyNet does not immediately recruit a replacement.
        ``"trial_maker"`` raises an error with ``recruit_mode=None`` or ``"n_trials"``.

    target_trials_per_node
        Target number of trials to recruit for each node. ``None`` (the
        default) means unlimited. When set, it must be a positive number;
        ``0`` is rejected. Requires ``recruit_mode="n_trials"``; passing it
        with any other mode raises an error. It does not cap selection: a node can
        receive more trials than its target, for example when participants
        recruited together finish at the same time.

    max_trials_per_block
        Determines the maximum number of trials that a participant will be allowed to experience in each block,
        including failed trials. Note that this number does not include repeat trials.

    allow_repeated_nodes
        Determines whether the participant can be administered the same node more than once.

    block_order
        The order in which the participant works through blocks: ``"random"``
        (the default), ``"listed"`` (the order in which blocks first appear in
        ``nodes``), a list of block names, or a function returning such a list.
        The function may take any of ``participant``, ``experiment`` and
        ``blocks``. See :ref:`trial_order`.

    node_order
        The order in which the participant receives nodes within a block:
        ``"balanced"`` (the default; nodes with the fewest trials from any
        participant first, excluding failed trials), ``"random"``,
        ``"listed"`` (the order of ``nodes``), a function returning the
        planned nodes, or a dict giving one of these values for every block.
        A function may take any of ``participant``, ``experiment``, ``block``
        and ``nodes``; returning fewer nodes than it was given also filters
        them. See :ref:`trial_order`.

    check_performance_at_end
        If ``True``, the participant's performance
        is evaluated at the end of the series of trials.
        Defaults to ``False``.
        See :meth:`~psynet.trial.main.TrialMaker.performance_check`
        for implementing performance checks.

    check_performance_every_trial
        If ``True``, the participant's performance
        is evaluated after each trial.
        Defaults to ``False``.
        See :meth:`~psynet.trial.main.TrialMaker.performance_check`
        for implementing performance checks.

    fail_trials_on_premature_exit
        See :class:`~psynet.trial.main.TrialMaker`.

    fail_trials_on_participant_performance_check
        See :class:`~psynet.trial.main.TrialMaker`. Defaults to ``True``.

    n_repeat_trials
        Number of repeat trials to present to the participant. These trials
        are typically used to estimate the reliability of the participant's
        responses. Repeat trials are presented at the end of the trial maker,
        after all blocks have been completed.
        Defaults to 0.

    choose_participant_group
        Only relevant if the trial maker uses nodes with non-default participant groups.
        In this case the experimenter is expected to supply a function that takes participant as an argument
        and returns the chosen participant group for that trial maker.
        For example, to randomly assign participants to one of two groups called g1 and g2, one could write::

            choose_participant_group=lambda participant: random.choice(["g1", "g2"])

        Similarly, to alternate participants between two groups, one could write::

            choose_participant_group=lambda participant: ["g1", "g2"][participant.id % 2]

    sync_group_type
        Optional SyncGroup type to use for synchronizing participant allocation to nodes.
        When this is set, then the ordinary node allocation logic will only apply to the 'leader'
        of each SyncGroup. The other members of this SyncGroup will follow that leader around,
        so that in every given trial the SyncGroup works on the same node together.
        The other ``sync_group_*`` options raise an error without it.

    sync_group_waiting_message, sync_group_max_wait_time, sync_group_max_wait_action, sync_group_late_after, sync_group_late_action, sync_group_also_leave, sync_group_newcomer_max_wait
        The message and time limits of the trial maker's own sync-group
        waits; see :class:`~psynet.trial.main.TrialMaker`.

    prepare_trials_in_advance
        If ``True``, create all of a participant's trials, in order, when they
        reach the trial maker, and send each trial page with the contents of
        the next :attr:`n_upcoming_trials` trials. A page whose modules
        return an ``update`` function then shows the next trial as soon as
        the participant answers, without waiting for the server; see
        :doc:`/code/trials/keeping_a_task_on_one_page`. Other trial pages,
        such as built-in prompts and controls, carry the next trials' pages
        rendered in advance, which the browser swaps in as the participant
        answers. Any trial page, such as one with an
        :class:`~psynet.modular_page.AudioPrompt`, also lists the files of
        the next trials' pages (their media and
        :attr:`~psynet.timeline.Page.prefetch_urls`), which the browser
        downloads while the participant works on the current trial; see
        :ref:`showing_the_next_trials_without_waiting`. All of this needs
        in-place timeline transitions, which are on by default. The response
        timeout counts from when the server first sends each trial's page;
        once one times out, the participant's trials waiting their turn
        fail with it. As every block is prepared at once,
        ``participant.module_state.block`` is the last block prepared while
        the trials are taken; read a trial's own block from ``trial.block``.
        Nodes are selected (``custom_node_filter``, ``select_node`` and the
        node order) when the trials are created, before any is answered, so
        selection can't adapt to the participant's answers. Likewise, the
        next trials' pages are built, with ``show_trial``, before the earlier
        trials are answered: if a trial's page shows something that earlier
        answers change, the browser replaces the page shown in advance with
        the server's once the server replies, so the participant briefly sees
        the old version.
        Can't be combined with
        ``sync_group_type``, ``check_performance_every_trial``,
        ``n_repeat_trials`` or ``recruit_mode="n_trials"``.
        Defaults to ``False``.

    Attributes
    ----------

    n_upcoming_trials : int
        With ``prepare_trials_in_advance``, how many of the next trials'
        contents or rendered pages each trial page carries (default = 2). The
        participant can
        be up to one more than this many answers ahead of the server, and
        this many trials' files are downloaded early. Each extra trial makes
        every trial request build one more page, so raise it only if large
        files need longer to download.

    check_timeout_interval_sec : float
        How often to check for trials that have timed out, in seconds (default = 30).
        Users are invited to override this.

    response_timeout_sec : float or None
        How long until a trial's response times out, in seconds (default = 300),
        or ``None`` for no limit
        (i.e. how long PsyNet will wait for the participant's response to a trial).
        This is a lower bound on the actual timeout
        time, which depends on when the timeout daemon next runs,
        which in turn depends on :attr:`~psynet.trial.main.TrialMaker.check_timeout_interval_sec`.
        Users are invited to override this.

    async_timeout_sec : float
        How long an async job may run before it times out, in seconds
        (default = 300), counted from when the job starts running, not
        from when it is queued.
        This is a lower bound on the actual timeout
        time, which depends on when the timeout daemon next runs,
        which in turn depends on :attr:`~psynet.trial.main.TrialMaker.check_timeout_interval_sec`.
        Users are invited to override this.

    network_query : sqlalchemy.orm.Query
        An SQLAlchemy query for retrieving all networks owned by the current trial maker.
        Can be used for operations such as the following: ``self.network_query.count()``.

    n_networks : int
        Returns the number of networks owned by the trial maker.

    networks : list
        Returns the networks owned by the trial maker.

    performance_threshold : float
        Threshold for the built-in performance check chosen by ``performance_check_type``,
        defaults to -1.0. The participant passes when the score (the summed trial scores,
        the proportion of non-failed trials, or the consistency) is at least this value.

    end_performance_check_waits : bool
        If ``True`` (default), then the final performance check waits until all trials no
        longer have any pending async jobs, and until trials that are ready
        to finalize have been finalized (so their scores are set).
    """

    def __init__(
        self,
        *,
        id_: str,
        trial_class,
        nodes: Optional[Union[callable, List["StaticNode"]]],
        expected_trials_per_participant: int | str,
        max_trials_per_participant: Optional[int | str] = None,
        recruit_mode: Optional[str] = None,
        target_n_participants: Optional[int] = None,
        n_participants_completion: Literal["experiment", "trial_maker"] = "experiment",
        target_trials_per_node: Optional[int] = None,
        max_trials_per_block: Optional[int] = None,
        allow_repeated_nodes: bool = False,
        block_order: Union[str, list, callable] = "random",
        node_order: Union[str, callable, dict] = "balanced",
        balance_across_nodes=None,
        check_performance_at_end: bool = False,
        check_performance_every_trial: bool = False,
        fail_trials_on_premature_exit: bool = False,
        fail_trials_on_participant_performance_check: bool = True,
        n_repeat_trials: int = 0,
        assets=None,
        choose_participant_group: Optional[callable] = None,
        sync_group_type: Optional[str] = None,
        sync_group_max_wait_time: Optional[Union[float, Callable]] = NoArgumentProvided,
        sync_group_max_wait_action: Literal["fail", "leave_group"] = "fail",
        sync_group_late_after: Optional[float] = None,
        sync_group_late_action: Optional[LateAction] = None,
        sync_group_also_leave: Optional[Sequence[str]] = None,
        sync_group_waiting_message=None,
        sync_group_newcomer_max_wait: Optional[float] = None,
        prepare_trials_in_advance: bool = False,
    ):
        _reject_removed_balance_argument(
            "balance_across_nodes", balance_across_nodes, "node_order"
        )
        if prepare_trials_in_advance and (
            sync_group_type
            or check_performance_every_trial
            or n_repeat_trials
            or recruit_mode == "n_trials"
        ):
            raise ValueError(
                "prepare_trials_in_advance=True can't be combined with "
                "sync_group_type, check_performance_every_trial, "
                "n_repeat_trials or recruit_mode='n_trials'."
            )
        self.prepare_trials_in_advance = prepare_trials_in_advance

        assert isinstance(expected_trials_per_participant, (int, float, str))
        if isinstance(expected_trials_per_participant, str):
            assert expected_trials_per_participant == "n_nodes"
            expected_trials_per_participant = (
                "n_start_nodes"  # form expected by ChainTrialMaker
            )

        assert max_trials_per_participant is None or isinstance(
            max_trials_per_participant, (int, float, str)
        )
        if isinstance(max_trials_per_participant, str):
            assert max_trials_per_participant == "n_nodes"
            max_trials_per_participant = (
                "n_start_nodes"  # form expected by ChainTrialMaker
            )

        if callable(nodes):
            if expected_trials_per_participant is None:
                raise ValueError(
                    "If nodes is a function, expected_trials_per_participant must be explicitly provided."
                )
        else:
            assert isinstance(nodes, list)
            if (
                isinstance(expected_trials_per_participant, (int, float))
                and expected_trials_per_participant > len(nodes)
                and not allow_repeated_nodes
            ):
                raise ValueError(
                    f"expected_trials_per_participant ({expected_trials_per_participant}) "
                    f"may not exceed len(nodes) ({len(nodes)}) "
                    "unless allow_repeated_nodes = True."
                )
            # We used to set chains_per_experiment to len(nodes) here, but this is
            # problematic if the nodes are generated from a function, because that
            # function has not yet been called. On reflection, it seems unnecessary to
            # set chains_per_experiment at all if start_nodes is being provided explicitly.
            # chains_per_experiment = len(nodes)

        if target_trials_per_node is not None and target_trials_per_node <= 0:
            raise ValueError(
                "target_trials_per_node must be a positive number, or None for unlimited."
            )
        target_argument = self._target_trials_argument
        if recruit_mode == "n_trials" and target_trials_per_node is None:
            raise ValueError(
                f"recruit_mode='n_trials' needs {target_argument}, the number "
                "of trials to recruit for each node."
            )
        if recruit_mode in (None, "n_participants") and target_trials_per_node:
            raise ValueError(
                f"{target_argument} only takes effect with "
                f"recruit_mode='n_trials', but recruit_mode is {recruit_mode!r}. "
                "Pass recruit_mode='n_trials' to recruit until every node has this "
                f"many trials, or remove {target_argument}."
            )

        chains_per_experiment = None

        if allow_repeated_nodes and (
            max_trials_per_participant is None and max_trials_per_block is None
        ):
            raise ValueError(
                "allow_repeated_nodes=True needs max_trials_per_participant or "
                "max_trials_per_block, so that participants do not repeat nodes forever."
            )

        super().__init__(
            id_=id_,
            start_nodes=nodes,
            trial_class=trial_class,
            network_class=StaticNetwork,
            node_class=StaticNode,
            recruit_mode=recruit_mode,
            target_n_participants=target_n_participants,
            n_participants_completion=n_participants_completion,
            expected_trials_per_participant=expected_trials_per_participant,
            max_trials_per_participant=max_trials_per_participant,
            max_trials_per_block=max_trials_per_block,
            chain_type="across",
            chains_per_participant=None,
            chains_per_experiment=chains_per_experiment,
            max_nodes_per_chain=1,
            trials_per_node=(
                target_trials_per_node
                if target_trials_per_node is not None
                else 1_000_000
            ),
            block_order=block_order,
            chain_order=node_order,
            allow_revisiting_networks_in_across_chains=allow_repeated_nodes,
            check_performance_at_end=check_performance_at_end,
            check_performance_every_trial=check_performance_every_trial,
            fail_trials_on_premature_exit=fail_trials_on_premature_exit,
            fail_trials_on_participant_performance_check=fail_trials_on_participant_performance_check,
            n_repeat_trials=n_repeat_trials,
            assets=assets,
            choose_participant_group=choose_participant_group,
            sync_group_type=sync_group_type,
            sync_group_max_wait_time=sync_group_max_wait_time,
            sync_group_max_wait_action=sync_group_max_wait_action,
            sync_group_late_after=sync_group_late_after,
            sync_group_late_action=sync_group_late_action,
            sync_group_also_leave=sync_group_also_leave,
            sync_group_waiting_message=sync_group_waiting_message,
            sync_group_newcomer_max_wait=sync_group_newcomer_max_wait,
        )

    n_upcoming_trials = 2

    def prepare_trial(self, experiment, participant):
        if not self.prepare_trials_in_advance:
            return super().prepare_trial(experiment, participant)
        trials = self.get_participant_trials(participant)
        trial = next((t for t in trials if not t.complete and not t.failed), None)
        if trial is not None:
            return trial, "available"
        # As without preparation, failed trials are replaced: they don't count
        # towards the limit, and their nodes can be chosen again.
        kept = [t for t in trials if not t.failed]
        failed_networks = {t.network_id for t in trials if t.failed} - {
            t.network_id for t in kept
        }
        state = participant.module_state
        state.participated_networks = [
            n for n in state.participated_networks if n not in failed_networks
        ]
        new_trials, status = self._prepare_trials(experiment, participant, len(kept))
        if new_trials:
            return new_trials[0], "available"
        return None, status

    def _prepare_trials(self, experiment, participant, n_existing):
        """Create the participant's next trials in the order that they will take them.

        Stops early if node selection has to wait, for example for a busy node;
        :meth:`prepare_trial` prepares the rest once these trials are done.
        Returns the new trials and the status that ended preparation.
        """
        trials = []
        status = "exit"
        while (
            self.max_trials_per_participant is None
            or n_existing + len(trials) < self.max_trials_per_participant
        ):
            trial, status = super().prepare_trial(experiment, participant)
            if trial is None:
                break
            trials.append(trial)
            # Selection skips nodes once their trials are finalized, which
            # trials waiting their turn aren't yet.
            participated = participant.module_state.participated_networks
            if trial.network_id not in participated:
                participated.append(trial.network_id)
        if trials:
            logger.info(
                "Prepared %i trials for participant %i.", len(trials), participant.id
            )
        return trials, status

    def _check_trials_shown_in_advance(self, participant):
        """Fail a test if the participant's trial pages were compared but none matched.

        Trials get a layout key once their pages are compared, so a pair of
        consecutive trials with keys, but none with the same key, means no
        trial could be shown in advance. A pair separated by a page between
        trials, which isn't compared, can still pass the check.
        """
        keys = [
            trial.layout_key
            for trial in self.get_participant_trials(participant)
            if not trial.failed
        ]
        compared = [
            (a, b) for a, b in zip(keys, keys[1:]) if a is not None and b is not None
        ]
        assert not compared or any(a and a == b for a, b in compared), (
            f"Trial maker {self.id!r} prepares trials in advance, but each "
            "trial's page had different HTML, JavaScript or js_vars from the "
            "previous one's, so none could be shown in advance. Put what changes "
            "between trials in the page's contents, which its page modules' "
            "update() receives; the server log names the trials. A picture in the "
            "page's HTML, as with ImagePrompt, makes every trial's page different. "
            "Pages without page modules are sent rendered instead and aren't checked."
        )

    def _swappable(self, page, experiment, participant):
        """Whether a rendered copy of ``page`` can be swapped in, with its answer sent in the background.

        Its answer reaches the server after the next trial is on screen, so the
        server must accept any answer. The first time each reason stops a
        page, the log says so.
        """
        reason = page._not_swappable_because()
        if reason is None and page._may_reject_answers():
            reason = (
                "the server may turn its answers down (validate or "
                "check_ready_for_response)"
            )
        logged = self.__dict__.setdefault("_logged_swap_reasons", set())
        if reason is not None and reason not in logged:
            logged.add(reason)
            logger.info(
                "Trial maker %r waits for the server before showing a %s, because %s.",
                self.id,
                type(page).__name__,
                reason,
            )
        return reason is None

    def _upcoming(self, trial, page, experiment, participant):
        # Without in-place transitions each reply reloads the page, which would
        # drop the answers given ahead and the files downloaded early.
        if not self.prepare_trials_in_advance or not get_config().get(
            "inplace_timeline_transitions"
        ):
            return None, None
        # A page that can be adopted as a predicted page gets a layout key,
        # even if its own feedback stops it from showing later trials. Other
        # pages get the rendered pages of the next trials, which the browser
        # swaps in as each trial is answered.
        page._pre_render_once()
        adoptable = page._show_in_advance()
        swappable = not adoptable and self._swappable(page, experiment, participant)
        shown = [] if adoptable or swappable else None
        media = {}
        ahead = shown is not None and not trial.gives_feedback(experiment, participant)
        trial_class = self.trial_class
        upcoming = (
            trial_class.query.filter(
                trial_class.participant_id == participant.id,
                trial_class.trial_maker_id == self.id,
                trial_class.id > trial.id,
                trial_class.complete.isnot(True),
                trial_class.failed.isnot(True),
            )
            .order_by(trial_class.id)
            .limit(self.n_upcoming_trials)
            .all()
        )
        previous = trial
        for following in upcoming:
            between = join(
                call_function_with_context(
                    self.show_after_trial,
                    experiment=experiment,
                    participant=participant,
                    trial=previous,
                )
            )
            previous = following
            pages = join(
                call_function_with_context(
                    following.show_trial,
                    experiment=experiment,
                    participant=participant,
                    trial_maker=self,
                    trial=following,
                )
            )
            for elt in between + pages:
                if isinstance(elt, Page):
                    # As before the page is shown, as it may set its contents.
                    elt._pre_render_once()
                    for media_type, urls in elt.prefetch_urls.items():
                        known = media.setdefault(media_type, [])
                        known.extend(url for url in urls if url not in known)
            next_page = pages[0] if not between and len(pages) == 1 else None
            ahead = (
                ahead
                and isinstance(next_page, Page)
                and (
                    next_page._show_in_advance()
                    and _same_layout(
                        trial, page, following, next_page, experiment, participant
                    )
                    if adoptable
                    else self._swappable(next_page, experiment, participant)
                )
            )
            if ahead:
                next_page._page_key = following._page_key
                if swappable:
                    next_page._rendered_in_advance = True
                shown.append(next_page)
                ahead = not following.gives_feedback(experiment, participant)
        # Page modules need the list, even if empty, to show the page itself.
        return (shown if adoptable else shown or None), media

